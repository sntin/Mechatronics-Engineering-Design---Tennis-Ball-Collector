void updateDistanceHeading()
{
	int left  = LEFT_SIGN  * SensorValue[encoderLeft];
	int right = RIGHT_SIGN * SensorValue[encoderRight];

	float dL = CM_PER_TICK * (left  - lastLeft);
	float dR = CM_PER_TICK * (right - lastRight);
	lastLeft = left;
	lastRight = right;

	float dDist = (dL + dR) / 2;
	float dHeadingDeg = (dL - dR) / TRACK_WIDTH * 180 / PI;

	// position: move along the average heading of this small step
	float midHeadingRad = (headingDeg + dHeadingDeg / 2) * PI / 180;
	xCM += dDist * cos(midHeadingRad);
	yCM += dDist * sin(midHeadingRad);

	distanceCM += dDist;
	headingDeg += dHeadingDeg;
}

// ---------------- compass ----------------
// true if this compass pin is active. Works on digital (0/1) and analog (0-4095) ports.
bool compassPin(tSensors pin)
{
	int v = SensorValue[pin];
	if (v > 1) v = (v > 2047) ? 1 : 0;
	return v == COMPASS_ACTIVE;
}

// RAW compass heading in degrees (0, 45, ... 315, clockwise from north), or -1 if the pins make no sense.
// Only the filter calls this: everything else uses readCompassDeg(), which is filtered.
int readCompassRaw()
{
	bool n = compassPin(compassN);
	bool e = compassPin(compassE);
	bool s = compassPin(compassS);
	bool w = compassPin(compassW);
	int active = (n ? 1 : 0) + (e ? 1 : 0) + (s ? 1 : 0) + (w ? 1 : 0);
	if (active == 0 || active > 2) return -1;  // nothing, or 3-4 pins at once: flicker
	if ((n && s) || (e && w)) return -1;       // opposite directions at once: impossible
	if (n && e) return 45;
	if (s && e) return 135;
	if (s && w) return 225;
	if (n && w) return 315;
	if (n) return 0;
	if (e) return 90;
	if (s) return 180;
	if (w) return 270;
	return -1;
}

float wrap180(float a)
{
	while (a > 180)   a -= 360;
	while (a <= -180) a += 360;
	return a;
}

