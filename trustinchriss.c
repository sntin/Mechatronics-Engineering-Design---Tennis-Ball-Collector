// ---------------- AT ALL TIMES: opponent ----------------
// OPPONENT AVOID version: only active during SECOND BALL (opponentActive). It no longer waits: it stops the
// drive, remembers which way the robot faced (the opponent is ahead of the robot), and missionSecondBall
// runs avoidOpponent(). Returns true when the opponent was seen.
long opponentIgnoreUntil = 0;
bool opponentActive = false;     // set by missionTask: true only while SECOND BALL runs
bool opponentSeen = false;       // set here, cleared by avoidOpponent()
float opponentHeadingDeg = 0;    // robot heading when the opponent was seen
bool checkOpponent()
{
	if (!opponentActive || nSysTime < opponentIgnoreUntil || !opponentClose()) return false;
	stopDrive();
	opponentSeen = true;
	opponentHeadingDeg = headingDeg;
	opponentIgnoreUntil = nSysTime + OPPONENT_IGNORE_MS;
	float h = wrap180(headingDeg);   // (into a variable first: ROBOTC gotcha)
	writeDebugStreamLine("OPPONENT ahead (raw %d) at x=%.0f y=%.0f, heading %.0f: avoiding", SensorValue[opponentSharp], xCM, yCM, h);
	return true;
}

// ---------------- AT ALL TIMES: line sensors ----------------
// Call once per loop while driving straight. direction 1 = forward, -1 = reversing.
// Only the LEADING pair is read (front pair forward, back pair reversing); the trailing pair is ignored.
// Returns true when the END line is reached: both leading sensors on the tape, or one of them inside the end zone
// (far end going forward, home reversing). One leading sensor outside the end zone = side line: recentre away
// from it right here (after END_CONFIRM_CM, in case the other one joins = end line at an angle), then carry on.
int watchSide = 0;       // -1 = tape only on the left sensors, +1 = only on the right
int watchSideHits = 0;
float watchSideStart = 0;
int endHits = 0;

int sharpLeftHits = 0;
int sharpRightHits = 0;
void resetSharpWatch()
{
	sharpLeftHits = 0;
	sharpRightHits = 0;
	clearSharpHistory();
}

void resetLineWatch()
{
	watchSide = 0;
	watchSideHits = 0;
	endHits = 0;
}

// true when the robot is close enough to the line it's driving toward that a single leading sensor = that line
bool inEndZone(int direction)
{
	if (direction > 0) return xCM > FIELD_MAX_X_CM - LINE_END_ZONE_CM;
	return xCM < HOME_SLOW_CM;
}

bool watchLines(int direction, float holdHeading)
{
	if (!USE_LINE_SENSORS) return false;
	// leading pair only
	bool leadL = (direction > 0) ? tapeFL() : tapeBL();
	bool leadR = (direction > 0) ? tapeFR() : tapeBR();

	// END line: both leading sensors, or one of them in the end zone
	bool endNow = (leadL && leadR) || ((leadL || leadR) && inEndZone(direction));
	endHits = endNow ? endHits + 1 : 0;
	if (endHits >= LINE_CONFIRM_READS)
	{
		writeDebugStreamLine("LINE: end line (%s L=%d R=%d) at x=%.0f y=%.0f", (direction > 0) ? "front" : "back", leadL, leadR, xCM, yCM);
		resetLineWatch();
		return true;
	}
	if (endNow) return false; // waiting for LINE_CONFIRM_READS

	int side = 0;
	if (leadL && !leadR) side = -1;
	else if (leadR && !leadL) side = 1;
	if (side != 0 && side == watchSide)
		watchSideHits++;
	else
	{
		watchSide = side;
		watchSideHits = (side != 0) ? 1 : 0;
		watchSideStart = distanceCM;
	}
	if (watchSide == 0 || watchSideHits < LINE_CONFIRM_READS) return false;

	// one leading sensor might be the end line reached at an angle: drive END_CONFIRM_CM more to see if the
	// other one joins
	if (abs(distanceCM - watchSideStart) < END_CONFIRM_CM) return false;

	stopDrive();
	writeDebugStreamLine("LINE: side line on the %s (%s sensor) at x=%.0f y=%.0f", (watchSide < 0) ? "LEFT" : "RIGHT", (direction > 0) ? "front" : "back", xCM, yCM);
	if (direction > 0) recenterAwayFrom(watchSide, holdHeading);
	else               recenterWhileReversing(watchSide, holdHeading);
	resetLineWatch();
	resetSharpWatch();
	return false;
}

// ---------------- ball finding ----------------
// what stopped a search move
#define STOP_BALL   1   // a Sharp sensor saw a ball (foundSide / peakRaw / peakHeadingDeg are set)
#define STOP_LINE   2   // end line
#define STOP_END    3   // distance / angle covered, or timeout, nothing found
#define STOP_INSIDE 4   // the ball Sharp says a ball is already inside
#define STOP_OPPONENT 5 // the opponent Sharp saw the opponent (SECOND BALL only)

// Call once per loop while moving. Returns +1 (right) / -1 (left) when ONE Sharp has seen something
// for CONFIRM_READS readings in a row, and sets foundSide / peakRaw / peakHeadingDeg. 0 otherwise.
// Both Sharps at once = wide object (ramp/wall): ignored.
int sharpCheck()
{
	int leftVal, rightVal;
	readSharps(leftVal, rightVal);
	sharpLeftHits  = (leftVal  > LEFT_BALL_THRESHOLD)  ? sharpLeftHits + 1  : 0;
	sharpRightHits = (rightVal > RIGHT_BALL_THRESHOLD) ? sharpRightHits + 1 : 0;
	bool leftSees  = sharpLeftHits  >= CONFIRM_READS;
	bool rightSees = sharpRightHits >= CONFIRM_READS;
	if (leftSees && rightSees)
	{
		writeDebugStreamLine("both Sharps see something (L=%d R=%d): ramp/wall, ignoring", leftVal, rightVal);
		sharpLeftHits = 0;
		sharpRightHits = 0;
		return 0;
	}
	if (!leftSees && !rightSees) return 0;
	foundSide = rightSees ? 1 : -1;
	peakRaw = rightSees ? rightVal : leftVal;
	peakHeadingDeg = headingDeg;
	return foundSide;
}

// The robot rolled/turned a bit after stopping, so measure the ball again standing still.
// If that look fails (or sees the other side), keep the reading taken while moving.
void refineBallStill()
{
	int movingSide = foundSide;
	int movingRaw = peakRaw;
	float movingHeading = peakHeadingDeg;
	if (!lookWhileStill() || foundSide != movingSide)
	{
		foundSide = movingSide;
		peakRaw = movingRaw;
		peakHeadingDeg = movingHeading;
	}
	writeDebugStreamLine("ball on the %s, raw=%d (%.0f cm), heading %.1f",
		(foundSide == 1) ? "RIGHT" : "LEFT", peakRaw, sharpToCM(peakRaw), peakHeadingDeg);
}

// Drive straight forward distCM (full power for the first fastCM without looking, then SEARCH_POWER
// watching both Sharps). Checks the ball Sharp, the line sensors and the opponent the whole way.
int driveForwardSearch(float distCM, float fastCM)
{
	float holdHeading = headingDeg;
	float startDist = distanceCM;
	int result = STOP_END;
	resetSharpWatch();
	resetLineWatch();
	ballSharpHits = 0;
	clearTimer(T2);
	while (distanceCM - startDist < distCM && time1[T2] < SEARCH_TIMEOUT_MS)
	{
		if (ballInside()) { result = STOP_INSIDE; break; }
		if (watchLines(1, holdHeading)) { result = STOP_LINE; break; }
		if (outOfField()) { writeDebugStreamLine("FIELD limit at x=%.0f y=%.0f", xCM, yCM); result = STOP_LINE; break; }
		if (checkOpponent()) { result = STOP_OPPONENT; break; }
		float gone = distanceCM - startDist;
		bool fast = gone < fastCM;
		int power = SEARCH_POWER;
		if (fast) power = DRIVE_POWER;
		else if (fastCM > 0 && gone < fastCM + SLOW_DOWN_CM)
			power = DRIVE_POWER - (int)((DRIVE_POWER - SEARCH_POWER) * (gone - fastCM) / SLOW_DOWN_CM);
		driveStraightStep(1, power, holdHeading);
		wait1Msec(10);
		if (fast) continue;
		turnFlap(); // the initial fast drive is done: flap on (stays on until the start switch is pressed again)
		if (sharpCheck() != 0) { result = STOP_BALL; break; }
	}
	stopDrive();
	wait1Msec(100); // let it stop
	if (result == STOP_BALL) refineBallStill();
	return result;
}

// Reverse straight distCM (SECOND BALL working back toward home) with the same line rules as going forward:
// back pair side line = recentre, home line = stop (STOP_LINE). Also stops if the ball Sharp sees a ball inside.
int driveBackSearch(float distCM)
{
	float holdHeading = headingDeg;
	float startDist = distanceCM;
	int result = STOP_END;
	resetLineWatch();
	ballSharpHits = 0;
	clearTimer(T2);
	while (startDist - distanceCM < distCM && time1[T2] < SEARCH_TIMEOUT_MS)
	{
		if (ballInside()) { result = STOP_INSIDE; break; }
		if (homeSwitchPressed()) { writeDebugStreamLine("back search: home switch pressed at x=%.0f", xCM); result = STOP_LINE; break; }
		if (watchLines(-1, holdHeading)) { result = STOP_LINE; break; }
		driveStraightStep(-1, SEARCH_POWER, holdHeading);
		wait1Msec(10);
	}
	stopDrive();
	wait1Msec(100);
	return result;
}

// Turn on the spot to targetDeg at SPIN_POWER while watching both Sharps and the ball Sharp.
// Use headingDeg + 360 for a full circle.
// same as turnLooking, but gives up after timeoutMs (used for the opponent spin)
int turnLookingMs(float targetDeg, int timeoutMs)
{
	int result = STOP_END;
	resetSharpWatch();
	ballSharpHits = 0;
	clearTimer(T2);
	while (time1[T2] < timeoutMs)
	{
		float error = targetDeg - headingDeg;
		if (abs(error) < TURN_TOLERANCE_DEG) break;
		if (ballInside()) { result = STOP_INSIDE; break; }
		int power = (error > 0) ? SPIN_POWER : -SPIN_POWER;
		setDrive(power, -power);
		wait1Msec(20);
		if (sharpCheck() != 0) { result = STOP_BALL; break; }
	}
	stopDrive();
	wait1Msec(TURN_PAUSE_MS); // let the compass settle
	if (result == STOP_BALL) refineBallStill();
	return result;
}

int turnLooking(float targetDeg)
{
	return turnLookingMs(targetDeg, SPIN_TIMEOUT_MS);
}

// Turn to face the ball found by the last look, then drive at it until the ball Sharp says it's
// inside (or the distance runs out, or the front line sensors see tape).
// Returns true if the ball is inside.
bool approachBall()
{
	float ballCM = sharpToCM(peakRaw);
	if (ballCM > 80) ballCM = 80;

	// ball position relative to the turning centre when it was measured
	// (bx = forward, by = out toward the sensor's side)
	float sideOffset    = (foundSide == 1) ? RIGHT_SIDE_OFFSET_CM    : LEFT_SIDE_OFFSET_CM;
	float forwardOffset = (foundSide == 1) ? RIGHT_FORWARD_OFFSET_CM : LEFT_FORWARD_OFFSET_CM;
	float trim          = (foundSide == 1) ? RIGHT_ALIGN_TRIM_DEG    : LEFT_ALIGN_TRIM_DEG;
	float aimRad = SENSOR_AIM_DEG * PI / 180;
	float bx = forwardOffset + ballCM * cos(aimRad);
	float by = sideOffset + ballCM * sin(aimRad);

	float turnDeg = angleFromForwardDeg(bx, by) + trim;
	float targetHeading = peakHeadingDeg + foundSide * turnDeg;
	writeDebugStreamLine("align: ball %.0f cm ahead, %.0f cm %s, turn to %.1f (now %.1f)",
		bx, by, (foundSide == 1) ? "right" : "left", targetHeading, headingDeg);
	turnToHeading(targetHeading);

	float approachCM = sqrt(bx * bx + by * by) - ROBOT_FRONT_CM + OVERSHOOT_CM;
	if (approachCM > MAX_APPROACH_CM) approachCM = MAX_APPROACH_CM;
	if (approachCM < 0) approachCM = 0;

	float holdHeading = headingDeg;
	float startDist = distanceCM;
	bool inside = false;
	ballSharpHits = 0;
	clearTimer(T3);
	while (distanceCM - startDist < approachCM && time1[T3] < DRIVE_TIMEOUT_MS)
	{
		if (ballInside()) { inside = true; break; }
		if (leadOnTape(1)) { writeDebugStreamLine("approach: front on the tape, stopping"); break; }
		if (outOfField()) { writeDebugStreamLine("approach: FIELD limit at x=%.0f y=%.0f, stopping", xCM, yCM); break; }
		if (checkOpponent()) break;   // opponent: stop the approach, missionSecondBall avoids it
		driveStraightStep(1, APPROACH_POWER, holdHeading);
		wait1Msec(20);
	}
	stopDrive();

	// the flap may still be pulling the ball in
	clearTimer(T3);
	while (!inside && time1[T3] < BALL_SETTLE_MS)
	{
		if (ballInside()) inside = true;
		wait1Msec(10);
	}
	writeDebugStreamLine("approach: %.0f cm, ball %s (ball Sharp raw %d)", distanceCM - startDist, inside ? "INSIDE" : "not inside", SensorValue[ballSharp]);

	// Missed, but the same Sharp still reads about the same as when it "saw the ball", after driving all the
	// way to where the ball was: it isn't a ball. Switch that Sharp off for the rest of this run.
	if (!inside && !opponentSeen)   // (stopped by the opponent = it never reached the ball, so no phantom check)
	{
		int nowRaw = (foundSide == 1) ? SensorValue[rightSharp] : SensorValue[leftSharp];
		int threshold = (foundSide == 1) ? RIGHT_BALL_THRESHOLD : LEFT_BALL_THRESHOLD;
		if (nowRaw > threshold && abs(nowRaw - peakRaw) < SHARP_STUCK_TOL)
		{
			if (foundSide == 1) rightSharpBad = true; else leftSharpBad = true;
			writeDebugStreamLine("WARNING: %s Sharp still reads %d after the approach (was %d): phantom, sensor OFF this run",
				(foundSide == 1) ? "RIGHT" : "LEFT", nowRaw, peakRaw);
		}
	}
	return inside;
}

// ---------------- release ----------------
// The release is a gate: open it, wait for the ball Sharp to say the ball is out (shake it out if not), close it.
void openGate()
{
	writeDebugStreamLine("release: opening the gate");
	motor[releaseMotor] = GATE_OPEN_POWER;
	wait1Msec(GATE_OPEN_MS);
	motor[releaseMotor] = 0;
}

void closeGate()
{
	writeDebugStreamLine("release: closing the gate");
	motor[releaseMotor] = -GATE_CLOSE_POWER;
	wait1Msec(GATE_CLOSE_MS);
	motor[releaseMotor] = 0;
}

// wait up to ms for the ball to leave: true once the ball Sharp has NOT seen it RELEASE_GONE_READS reads in a row
bool waitBallGone(int ms)
{
	int clear = 0;
	clearTimer(T3);
	while (time1[T3] < ms)
	{
		clear = ballSharpSees() ? 0 : clear + 1;
		if (clear >= RELEASE_GONE_READS) return true;
		wait1Msec(10);
	}
	return false;
}

// twist left/right on the spot a few times (short and hard, so it shakes more than it turns)
void releaseWiggle()
{
	for (int i = 0; i < RELEASE_WIGGLES; i++)
	{
		setDrive(RELEASE_WIGGLE_POWER, -RELEASE_WIGGLE_POWER);
		wait1Msec(RELEASE_WIGGLE_MS);
		setDrive(-RELEASE_WIGGLE_POWER, RELEASE_WIGGLE_POWER);
		wait1Msec(RELEASE_WIGGLE_MS);
	}
	stopDrive();
}

// forward a little, then slam back into the home wall
void releaseShake(float holdHeading)
{
	float startDist = distanceCM;
	clearTimer(T3);
	while (distanceCM - startDist < RELEASE_FWD_CM && time1[T3] < 1000)
	{
		driveStraightStep(1, RELEASE_FWD_POWER, holdHeading);
		wait1Msec(10);
	}
	long pressedAt = -1;
	clearTimer(T3);
	while (time1[T3] < RELEASE_BACK_TIMEOUT_MS)
	{
		if (homeSwitchPressed())
		{
			if (pressedAt < 0) pressedAt = nSysTime;
			else if (nSysTime - pressedAt >= RELEASE_PUSH_MS) break;
		}
		driveStraightStep(-1, RELEASE_BACK_POWER, holdHeading);
		wait1Msec(10);
	}
	stopDrive();
}

void releaseBall()
{
	openGate();
	writeDebugStreamLine("release: gate open, holding %d ms (fixed)", GATE_HOLD_MS);
	wait1Msec(GATE_HOLD_MS);   // fixed wait, ignores the ball Sharp
	closeGate();
}

// ---------------- MISSION STATES ----------------
#define STATE_FIRST_BALL  1
#define STATE_RETURN      2
#define STATE_SECOND_BALL 3

// At home the robot is square against the home wall, so it faces exactly forward (the start heading)
// and it's at the start point: snap the encoder heading and x/y to that.
void snapAtHome()
{
	int c = readCompassDeg();
	hogCPU();   // don't let the odometry task run halfway through this
	headingDeg -= wrap180(headingDeg);
	xCM = 0;
	yCM = 0;
	compassNow = -1;
	compassSteady = -1;
	releaseCPU();
	writeDebugStreamLine("HOME: heading snapped to forward, x/y reset to 0 (compass reads %d, start was %d)", c, (int)startCompassDeg);
	writeDebugStreamLine("HOME: compass flicker readings ignored so far: %d", compassFlickerCount);
	if (startCompassDeg >= 0 && c != (int)startCompassDeg) writeDebugStreamLine("HOME: WARNING compass doesn't match the start reading");
}

// FIRST BALL: drive straight to the end; a ball on the way = go and get it.
// Not inside yet = back up a bit, spin a full circle looking, go for what it sees. Repeat until inside.
void missionFirstBall()
{
	writeDebugStreamLine("=== FIRST BALL ===");
	int r = driveForwardSearch(SEARCH_TOTAL_CM, FAST_DRIVE_CM);
	turnFlap(); // in case the drive stopped before the fast part was over (ball inside, line, opponent, timeout)
	while (r != STOP_INSIDE)
	{
		if (r == STOP_BALL && approachBall()) return;

		driveStraightCM(-BALL_SEARCH_BACKUP_CM, SEARCH_POWER, true); // stops if a back sensor hits tape
		r = turnLooking(headingDeg + 360);
		if (r == STOP_END)
		{
			// nothing in a full circle: move to a new spot and look again
			turnToNorth();
			if (xCM > SECTION_CM) r = driveBackSearch(SECTION_CM); // side lines recentre, home line stops
			else r = driveForwardSearch(SECTION_CM, 0);
		}
	}
}

// SECOND BALL: from home, drive forward one section at a time and sweep left and right at each stop.
// At the far end it works back toward home the same way, and so on, until a ball is inside.
// OPPONENT AVOID: back up, spin-search for up to OPP_SPIN_MS, then search away from where the opponent was.
// The opponent Sharp looks forward, so the opponent was in the direction the robot faced (opponentHeadingDeg).
// Ahead/north-ish (it's further out in the field) -> search back toward home. Behind/south-ish -> search further out.
// Returns the result of the last move (STOP_BALL / STOP_INSIDE / STOP_OPPONENT / STOP_LINE / STOP_END).
int avoidOpponent()
{
	opponentSeen = false;
	writeDebugStreamLine("OPPONENT: backing off %.0f cm, spinning up to %d ms, then searching away from it", OPP_BACKUP_CM, OPP_SPIN_MS);
	driveStraightCM(-OPP_BACKUP_CM, SEARCH_POWER, true);   // stops early if a back sensor hits tape
	float spinTo = headingDeg + 360;
	int r = turnLookingMs(spinTo, OPP_SPIN_MS);
	if (r == STOP_BALL || r == STOP_INSIDE) return r;
	turnToNorth();
	float oppRad = opponentHeadingDeg * PI / 180;
	if (cos(oppRad) > 0)
	{
		writeDebugStreamLine("OPPONENT was ahead: searching %.0f cm back toward home", OPP_AVOID_CM);
		r = driveBackSearch(OPP_AVOID_CM);
	}
	else
	{
		writeDebugStreamLine("OPPONENT was behind: searching %.0f cm further out", OPP_AVOID_CM);
		r = driveForwardSearch(OPP_AVOID_CM, 0);
	}
	return r;
}

void missionSecondBall()
{
	writeDebugStreamLine("=== SECOND BALL: waiting %d ms ===", SECOND_BALL_DELAY_MS);
	wait1Msec(SECOND_BALL_DELAY_MS);   // pause between the first ball's return and the second ball's search
	writeDebugStreamLine("=== SECOND BALL ===");
	turnToNorth();
	// same as FIRST BALL: drive forward to the boundary (end line / field limit / SEARCH_TOTAL_CM),
	// searching the whole way (except the first SECOND_FAST_DRIVE_CM, if that's above 0)
	int r = driveForwardSearch(SEARCH_TOTAL_CM, SECOND_FAST_DRIVE_CM);
	while (r != STOP_INSIDE)
	{
		if (opponentSeen) { r = avoidOpponent(); continue; }
		if (r == STOP_BALL)
		{
			if (approachBall()) return;
			if (opponentSeen) { r = avoidOpponent(); continue; }   // the approach was stopped by the opponent
		}

		driveStraightCM(-BALL_SEARCH_BACKUP_CM, SEARCH_POWER, true); // back up a little (stops if a back sensor hits tape)
		r = turnLooking(headingDeg + 360);                          // spin 360 looking
		if (r == STOP_END)
		{
			// nothing in a full circle: move to a new spot and look again
			turnToNorth();
			if (xCM > SECTION_CM) r = driveBackSearch(SECTION_CM); // side lines recentre, home line stops
			else r = driveForwardSearch(SECTION_CM, 0);
		}
	}
}

// RETURN BALL: face forward (the start heading), reverse until home, snap heading/position, release the ball.
// Home = home switch pressed AND both back line sensors (LB + RB) on the tape
// (lines only if USE_LINE_SENSORS).
// If the switch stays pressed for HOME_SWITCH_ONLY_MS but the lines don't agree, it counts as home anyway
// (it can't reverse any further), with a warning.
// compass reading once it has stayed the same for COMPASS_STABLE_MS (robot standing still), -1 if it won't settle
int steadyCompassDeg()
{
	int c = readCompassDeg();
	long since = nSysTime;
	clearTimer(T3);
	while (time1[T3] < 1500)
	{
		int now = readCompassDeg();
		if (now != c) { c = now; since = nSysTime; }
		else if (c >= 0 && nSysTime - since >= COMPASS_STABLE_MS) return c;
		wait1Msec(10);
	}
	return -1;
}

// Turn until the compass reads N. The N range is narrow, so reading N = facing exactly north:
// the encoder heading is set to exactly north (0) right there. Returns false if it never read N.
bool turnToCompassNorth()
{
	if (!USE_COMPASS || startCompassDeg < 0) { turnToNorth(); return false; }
	int northDeg = (int)FORWARD_COMPASS_DEG;
	// COMPASS FIRST (2026-11-13): read the compass, then turn the difference to north with the encoders.
	// The 1490 only gives 8 directions (45 deg steps), so this first turn is only good to about +-22 deg;
	// the nudge loop below then finds N exactly. If the compass won't settle, use the encoder north instead.
	int c0 = steadyCompassDeg();
	if (c0 < 0)
	{
		writeDebugStreamLine("north: compass won't settle, encoder turn to north instead");
		turnToNorth();
	}
	else if (c0 != northDeg)
	{
		float diff = wrap180(c0 - northDeg);   // + = facing east of north, so turn LEFT by diff
		float target = headingDeg - diff;      // (into a variable first: ROBOTC gotcha)
		writeDebugStreamLine("north: compass reads %d, turning %.0f deg with the encoders", c0, -diff);
		turnToHeading(target);
	}
	float step = NORTH_STEP_DEG;
	int lastSide = 0;
	int c = -1;
	for (int i = 0; i <= NORTH_STEP_TRIES; i++)
	{
		c = steadyCompassDeg();
		if (c < 0) { writeDebugStreamLine("north: compass won't settle, using encoders only"); return false; }
		if (c == northDeg)
		{
			float corr = -wrap180(headingDeg);
			hogCPU();
			headingDeg += corr;   // exactly north (keeps the same number of whole turns)
			releaseCPU();
			writeDebugStreamLine("north: compass reads N after %d nudge(s), heading set to north (corrected %.1f deg)", i, corr);
			return true;
		}
		if (i == NORTH_STEP_TRIES) break;
		int side = (wrap180(c - northDeg) > 0) ? 1 : -1;   // +1 = still east of north, -1 = west
		if (lastSide != 0 && side != lastSide) step = step / 2;   // went past N: smaller nudges
		if (step < NORTH_MIN_STEP_DEG) step = NORTH_MIN_STEP_DEG;
		lastSide = side;
		turnToHeading(headingDeg - side * step);
	}
	writeDebugStreamLine("north: compass still says %d after %d nudges, using encoders only", c, NORTH_STEP_TRIES);
	turnToNorth();
	return false;
}

// face forward (= north) to go home
void faceForward()
{
	turnToCompassNorth();
}

// START: turn to face north (the start heading came from the compass reading)
void faceNorthAtStart()
{
	turnToCompassNorth();
}

// RETURN BALL in SECTIONS: reverse home RETURN_SECTION_CM at a time. After each section it stops,
// lets the compass settle and turns until the compass reads N, which sets the heading to exactly north.
// Once x < RETURN_LAST_CM it doesn't stop any more and just reverses the last stretch into home.
// Home = home switch + back lines (switch alone for HOME_SWITCH_ONLY_MS also counts). Side lines recentre.
// The timeout counts reversing time only (the stops for the compass don't use it up).
void checkNorthSection()
{
	stopDrive();
	wait1Msec(RETURN_STOP_MS);   // let the robot and the compass settle
	writeDebugStreamLine("RETURN: section done at (%.0f, %.0f), heading %.1f: compass check", xCM, yCM, wrap180(headingDeg));
	turnToCompassNorth();
}

// SIDE START: going home, after facing north angle the nose a bit:
// started LEFT (startSide -1) = nose LEFT, started RIGHT (1) = nose RIGHT, normal (0) = straight north
bool returnAngleUsed = false;   // the angle is used ONCE per run (first face-north of the first return)
void angleForReturn()
{
	if (startSide == 0 || returnAngleUsed) return;
	returnAngleUsed = true;
	float aim = nearestHeading(0) + startSide * RETURN_ANGLE_DEG;
	writeDebugStreamLine("RETURN: started %s, nose %.0f deg %s", (startSide < 0) ? "LEFT" : "RIGHT", RETURN_ANGLE_DEG, (startSide < 0) ? "left" : "right");
	turnToHeading(aim);
}

void missionReturn()
{
	writeDebugStreamLine("=== RETURN BALL === from (%.0f, %.0f), sections of %.0f cm", xCM, yCM, RETURN_SECTION_CM);
	faceForward();
	angleForReturn();          // SIDE START: nose a bit left/right (straight for a normal start)
	float holdHeading = headingDeg;
	resetLineWatch();
	int homeHits = 0;
	bool home = false;
	long switchSince = -1;
	float sectionStart = distanceCM;
	int section = 1;
	// reversing time only: T2 is cleared every loop and added up here, and it's cleared again after each
	// compass stop, so the stops are never counted
	long reverseMs = 0;
	clearTimer(T2);
	while (reverseMs < RETURN_TIMEOUT_MS)
	{
		reverseMs += time1[T2];
		clearTimer(T2);
		bool sw = homeSwitchPressed();
		// HOME = either home switch (in5 or in7) pressed, 2 reads in a row (back lines no longer needed)
		homeHits = sw ? homeHits + 1 : 0;
		if (homeHits >= 2) { home = true; break; }
		if (!sw) switchSince = -1;
		else if (switchSince < 0) switchSince = nSysTime;
		else if (nSysTime - switchSince > HOME_SWITCH_ONLY_MS)
		{
			writeDebugStreamLine("HOME: switch pressed but back lines not both on the tape, counting it as home");
			home = true;
			break;
		}

		// end of a section (not in the last stretch, and not while the switch is touching): stop and check the compass
		if (!sw && abs(distanceCM - sectionStart) >= RETURN_SECTION_CM && xCM > RETURN_LAST_CM)
		{
			checkNorthSection();   // plain north from here on (the angle is only used once)
			holdHeading = headingDeg;
			resetLineWatch();
			homeHits = 0;
			switchSince = -1;
			sectionStart = distanceCM;
			section++;
			clearTimer(T2);   // the stop doesn't count toward the timeout
			writeDebugStreamLine("RETURN: section %d from (%.0f, %.0f)", section, xCM, yCM);
		}

		// side lines: recentre and carry on. The home line it reports is ignored here (home = switch + lines,
		// checked above). Not while the switch is pressed: it's against the home wall, so no recentring.
		if (!sw) watchLines(-1, holdHeading);
		// slow down near home: full RETURN_POWER, ramp down over HOME_RAMP_CM, then HOME_BRAKE_POWER
		int power = RETURN_POWER;
		if (xCM < HOME_BRAKE_CM) power = HOME_BRAKE_POWER;
		else if (xCM < HOME_BRAKE_CM + HOME_RAMP_CM)
			power = HOME_BRAKE_POWER + (int)((RETURN_POWER - HOME_BRAKE_POWER) * (xCM - HOME_BRAKE_CM) / HOME_RAMP_CM);
		driveStraightStep(-1, power, holdHeading);
		wait1Msec(20);
	}
	stopDrive();
	if (!home) writeDebugStreamLine("RETURN: WARNING timed out before home (%d ms reversing), at (%.0f, %.0f) - treating it as home", reverseMs, xCM, yCM);
	snapAtHome();   // TIMEOUT SNAP (2026-11-13): home OR timed out -> x/y = 0, heading = north
	releaseBall();
}


// The whole mission runs as its own task, so main can stop it at any moment.
// MISSION: FIRST BALL, RETURN, SECOND BALL, RETURN (or just FIRST BALL, RETURN if MISSION_BALLS = 1)
bool missionRunning = false;
task missionTask()
{
	stopFlap(); // flap stays OFF until the initial fast drive is done (turned on in driveForwardSearch)
	leftSharpBad = false;
	rightSharpBad = false;
	if (!MANUAL_NORTH_START) faceNorthAtStart(); // forward is always north: turn to it before anything else
	// (MANUAL_NORTH_START = true: you faced it north by hand, so it just drives forward)
	returnAngleUsed = false;
	opponentActive = false;
	opponentSeen = false;
	int state = STATE_FIRST_BALL;
	int ballsHome = 0;
	// REPEAT_SECOND_BALL: SECOND BALL + RETURN forever, until the start switch stops the mission
	while (REPEAT_SECOND_BALL || ballsHome < MISSION_BALLS)
	{
		if (state == STATE_FIRST_BALL)
		{
			missionFirstBall();
			state = STATE_RETURN;
		}
		else if (state == STATE_SECOND_BALL)
		{
			opponentActive = true;    // the opponent Sharp is only used during SECOND BALL
			missionSecondBall();
			opponentActive = false;
			opponentSeen = false;
			state = STATE_RETURN;
		}
		else // STATE_RETURN
		{
			missionReturn();
			ballsHome++;
			state = STATE_SECOND_BALL;
		}
	}
	writeDebugStreamLine("=== MISSION DONE (%d ball%s home) ===", ballsHome, (ballsHome == 1) ? "" : "s");
	missionRunning = false;
}

void stopEverything()
{
	stopDrive();
	stopFlap();
	motor[releaseMotor] = 0;
}


// Turn until the compass reads compassDeg (0 = N, 90 = E, 180 = S, 270 = W, diagonals 45/135/225/315),
// same method as turnToCompassNorth: encoder turn, then nudge until the compass reads it, then snap heading.
bool turnToCompassHeading(int compassDeg)
{
	float targetH = wrap180(compassDeg - FORWARD_COMPASS_DEG);
	float h = nearestHeading(targetH);
	turnToHeading(h);
	if (!USE_COMPASS || startCompassDeg < 0) return false;
	float step = NORTH_STEP_DEG;
	int lastSide = 0;
	int c = -1;
	for (int i = 0; i <= NORTH_STEP_TRIES; i++)
	{
		c = steadyCompassDeg();
		if (c < 0) return false;
		if (c == compassDeg)
		{
			float corr = wrap180(targetH - headingDeg);
			hogCPU();
			headingDeg += corr;
			releaseCPU();
			return true;
		}
		if (i == NORTH_STEP_TRIES) break;
		int side = (wrap180(c - compassDeg) > 0) ? 1 : -1;
		if (lastSide != 0 && side != lastSide) step = step / 2;
		if (step < NORTH_MIN_STEP_DEG) step = NORTH_MIN_STEP_DEG;
		lastSide = side;
		turnToHeading(headingDeg - side * step);
	}
	h = nearestHeading(targetH);
	turnToHeading(h);
	return false;
}
const int REVERSE_HEADING_POWER = 80;   // TUNE
// Face compassDeg, then reverse distCM holding that heading. Counts encoder ticks directly.
bool reverseOnCompassHeading(int compassDeg, float distCM, int timeoutMs)
{
	turnToCompassHeading(compassDeg);
	float hold = headingDeg;
	int startL = SensorValue[encoderLeft];
	int startR = SensorValue[encoderRight];
	float targetTicks = distCM / CM_PER_TICK;
	clearTimer(T4);
	while (time1[T4] < timeoutMs)
	{
		int dl = SensorValue[encoderLeft] - startL;
		int dr = SensorValue[encoderRight] - startR;
		if (dl < 0) dl = -dl;
		if (dr < 0) dr = -dr;
		float ticks = (dl + dr) / 2.0;
		if (ticks >= targetTicks)
		{
			stopDrive();
			writeDebugStreamLine("REVERSE: done, %.0f ticks = %.0f cm", ticks, ticks * CM_PER_TICK);
			return true;
		}
		driveStraightStep(-1, REVERSE_HEADING_POWER, hold);
		wait1Msec(20);
	}
	stopDrive();
	writeDebugStreamLine("REVERSE: TIMEOUT, encoders L %d R %d", SensorValue[encoderLeft] - startL, SensorValue[encoderRight] - startR);
	return false;
}

// Press the start switch to run the mission. Press it again while it's running to STOP.
// After a stop (or when the mission is done) it waits for the next press, so you can run it again
// without restarting the program.
task main()
{
	clearDebugStream();

	while (true)
	{
		waitForStartButton();

		motor[releaseMotor] = -40;
		wait1Msec(100);
		motor[releaseMotor] = 0;
		resetOdometry();
		startTask(odometry);
		if (TEST_TURN90)
		{
			// test: right 90, pause, left 90 (should end where it started)
			wait1Msec(300);
			turnRight90();
			writeDebugStreamLine("turn90 test: after right heading = %f", headingDeg);
			wait1Msec(1000);
			turnLeft90();
			writeDebugStreamLine("turn90 test: after left heading = %f", headingDeg);
			stopEverything();
			stopTask(odometry);
			continue;
		}
		if (TEST_REVERSE)
		{
			wait1Msec(300);
			reverseOnCompassHeading(0, 50, 3000);   // face NORTH, reverse 50 cm, max 3 s
			stopEverything();
			stopTask(odometry);
			continue;
		}
		missionRunning = true;
		startTask(missionTask);

		while (missionRunning && !startPressed()) wait1Msec(10);
		if (missionRunning)
		{
			stopTask(missionTask);
			missionRunning = false;
			writeDebugStreamLine("STOP: start switch pressed");
			stopEverything();
			while (startPressed()) wait1Msec(10); // wait for your hand to let go
			wait1Msec(500);
		}
		else
		{
			// mission done: wheels and gate stop, but the flap keeps running until the start switch is pressed
			stopDrive();
			motor[releaseMotor] = 0;
			if (flapOn)
			{
				writeDebugStreamLine("mission done: flap still on, press the start switch to stop it");
				while (!startPressed()) wait1Msec(10);
				writeDebugStreamLine("STOP: start switch pressed, flap off");
				stopEverything();
				while (startPressed()) wait1Msec(10);
				wait1Msec(500);
			}
		}
		stopEverything();
		stopTask(odometry);
	}
	}
