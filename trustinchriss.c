// SIDE START (2026-11-12): 3 ways to start. Press and HOLD any of them as long as you like;
// the robot starts the moment you LET GO (plus START_RELEASE_DELAY_MS, 0 = straight away).
//   start switch (in3)  = normal mission, SECOND BALL goes straight north (startSide = 0)
//   home switch 1 (in5) = robot starts on the LEFT:  going home, nose RETURN_ANGLE_DEG to the LEFT  (startSide = -1)
//   home switch 2 (in7) = robot starts on the RIGHT: going home, nose RETURN_ANGLE_DEG to the RIGHT (startSide = 1)
// The robot must NOT be touching the wall with its back (home) switches when you start it.
bool homeSwitch1Pressed() { return SensorValue[homeSwitch]  < START_PRESSED_BELOW; }
bool homeSwitch2Pressed() { return SensorValue[homeSwitch2] < START_PRESSED_BELOW; }

void waitForStartButton()
{
	writeDebugStreamLine("press start (in3) = normal, home switch 1 (in5) = robot LEFT, home switch 2 (in7) = robot RIGHT");
	while (!startPressed() && !homeSwitch1Pressed() && !homeSwitch2Pressed()) wait1Msec(10);
	if (startPressed())            startSide = 0;
	else if (homeSwitch1Pressed()) startSide = -1;
	else                           startSide = 1;
	// hold it as long as you like: wait until ALL three are let go
	while (startPressed() || homeSwitch1Pressed() || homeSwitch2Pressed()) wait1Msec(10);
	if (startSide < 0)      writeDebugStreamLine("released: robot on the LEFT (SECOND BALL angles right)");
	else if (startSide > 0) writeDebugStreamLine("released: robot on the RIGHT (SECOND BALL angles left)");
	else                    writeDebugStreamLine("released: normal start");
	if (START_RELEASE_DELAY_MS > 0) wait1Msec(START_RELEASE_DELAY_MS);
}



